// trip-decision-read.js — #Place world-class #3 (god-module decomposition),
// carve 1. The DECISION READ accessors, extracted verbatim from app-main.js
// (following the PD.401g precedent: discovery-adapter.js — "functions unchanged,
// still run as globals, only their home moved"). These are the single read path
// for "what did the user decide here":
//
//   _keepOf(p)        → derived keep (decision log → persisted _keep → origin default)
//   _decisionOf(p)    → the user's decision record for a place, or null
//   _roleOf(p,isStay) → derived role (decision.role → suggested → kind default)
//
// PURE reads. They still run as GLOBALS via auto-expose (app-main + the picker/
// trip-ui modules call them as bare globals at runtime); only the home moved.
// The app-main globals they read (_tb, window._placeOrigin, MaxDecisions) are
// available at call time (runtime), never at this module's load.

function _keepOf(p){
  if (!p) return false;
  if (typeof MaxDecisions === "undefined" || !MaxDecisions || typeof MaxDecisions.keepOf !== "function") return !!p._keep;
  var _o = (typeof window._placeOrigin === "function") ? window._placeOrigin(p) : (p._origin || "max");
  var _d = (typeof _tb !== "undefined" && _tb && _tb._decisions && typeof _tb._decisions.get === "function") ? _tb._decisions.get(p.place) : null;
  if (_d) return MaxDecisions.keepOf({ origin: _o }, _d);
  // No decision-log entry — prefer the PERSISTED decision (stored _keep) over a
  // blind origin default. (B1.1 proved the candidate snapshot isn't universally
  // complete — candidates:[] on loaded/seeded trips — so _keep is load-bearing
  // here and stays; see OBJECT-MODEL.md §7.)
  if (typeof p._keep === "boolean") return p._keep;
  return MaxDecisions.keepOf({ origin: _o }, null);
}

function _decisionOf(p){
  if (!p || !p.place) return null;
  if (typeof _tb === "undefined" || !_tb || !_tb._decisions || typeof _tb._decisions.get !== "function") return null;
  return _tb._decisions.get(p.place) || null;
}

function _roleOf(p, isStay){
  if (!p) return null;
  if (typeof MaxDecisions === "undefined" || !MaxDecisions || typeof MaxDecisions.roleOf !== "function") {
    if (p._waysideFromHub) return "onway";
    if (p._isDayTrip) return "daytrip";
    return isStay ? "stay" : "see";
  }
  var _o = (typeof window._placeOrigin === "function") ? window._placeOrigin(p) : (p._origin || "max");
  return MaxDecisions.roleOf({ origin: _o, kind: isStay ? "destination" : "sight" }, _decisionOf(p));
}

export { _keepOf, _decisionOf, _roleOf };

